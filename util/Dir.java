package org.firstinspires.ftc.teamcode.util;

/**
 * An enum that represents cardinal and intercardinal directions, as well as rotational directions.
 *
 * For our robot specifically, front is defined as the front of the collector.
 * @author Guinea
 */

public enum Dir {

    forward,
    backward,
    right,
    left,
    frontleft,
    frontright,
    backleft,
    backright,
    clockwise,
    counterclock
}
